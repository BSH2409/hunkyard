import { test, expect } from '@playwright/test';

test('the Preferences tab shows rules, pipeline, persona and activity', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('.loading')).toBeHidden();
  await page.click('#settingsToggle');
  await expect(page.locator('#tab-yard')).toHaveText(/^Preferences\d*$/);
  await page.click('#tab-yard');
  const yard = page.locator('#yardPane .yard');
  await expect(yard.locator('.yard-nav-item')).toHaveText(['This review', 'Rules', 'Pipeline', 'Persona', 'Loads', 'Activity', 'Insights', /^Health\d*$/]);

  await yard.locator('[data-yard-view="rules"]').click();
  await expect(yard.locator('.yard-row', { hasText: 'Write method definitions over multiple lines.' })).toBeVisible();
  await expect(yard.locator('.yard-row', { hasText: 'Keep test files out of commits.' }).locator('.yard-label--repo')).toHaveText('orion');

  // Persona files render as markdown, without the generated header.
  await yard.locator('[data-yard-view="persona"]').click();
  await expect(yard.locator('[data-persona-file="core.md"]')).toBeVisible();
  await yard.locator('[data-persona-file="ruby.md"]').click();
  await expect(yard.locator('.yard-file-view')).toContainText('multiple lines');
  await expect(yard.locator('.yard-markdown li').first()).toBeVisible();
  await expect(yard.locator('.yard-file-view')).not.toContainText('Generated by');

  // Pipeline lists the rules in each column; Run maintenance lives here, not on Health.
  await yard.locator('[data-yard-view="pipeline"]').click();
  const active = yard.locator('.yard-column', { has: page.locator('.yard-column-head', { hasText: 'Active' }) });
  await expect(active.locator('.yard-card', { hasText: 'Write method definitions over multiple lines.' })).toBeVisible();
  // The fixture has a captured observation waiting, so maintenance is offered here.
  await expect(yard.locator('.yard-column', { has: page.locator('.yard-column-head', { hasText: 'Captured' }) }).locator('.yard-card')).not.toHaveCount(0);
  await expect(yard.locator('[data-yard-action="maintenance"]')).toBeVisible();
  await yard.locator('[data-yard-view="health"]').click();
  await expect(yard.locator('.yard-list')).toBeVisible();
  await expect(yard.locator('[data-yard-action="maintenance"]')).toHaveCount(0);

  await yard.locator('[data-yard-view="activity"]').click();
  await expect(yard.locator('.yard-event-kind', { hasText: 'learned' }).first()).toBeVisible();
});

test('the Preferences tab is wide, its views are real tabs pinned above the content', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 700 });
  await page.goto('/');
  await expect(page.locator('.loading')).toBeHidden();
  await page.click('#settingsToggle');
  const dialog = page.locator('.settings-dialog');
  // One size for every tab, wide enough for the Preferences board.
  await page.click('#tab-settings');
  await dialog.evaluate((el) => Promise.all(el.getAnimations().map((a) => a.finished)));
  const settingsBox = (await dialog.boundingBox())!;
  await page.click('#tab-yard');
  const yardBox = (await dialog.boundingBox())!;
  expect(yardBox.width).toBeGreaterThan(1000);
  expect(yardBox.width).toBe(settingsBox.width);
  expect(yardBox.height).toBe(settingsBox.height);

  const yard = page.locator('#yardPane .yard');
  const tabs = yard.getByRole('tablist', { name: 'Preferences views' });
  await expect(tabs.getByRole('tab')).toHaveCount(8);
  await expect(tabs.getByRole('tab', { name: 'This review' })).toHaveAttribute('aria-selected', 'true');
  await tabs.getByRole('tab', { name: 'This review' }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(tabs.getByRole('tab', { name: 'Rules' })).toHaveAttribute('aria-selected', 'true');
  await expect(tabs.getByRole('tab', { name: 'Rules' })).toBeFocused();
  await expect(yard.getByRole('tabpanel')).toHaveAttribute('aria-labelledby', 'yard-tab-rules');

  // The bar stays at the top of the dialog while the view scrolls under it.
  const content = page.locator('.settings-content');
  const top = (await content.boundingBox())!.y;
  await content.evaluate((el) => { el.scrollTop = el.scrollHeight; });
  await expect.poll(async () => Math.abs((await yard.locator('.yard-bar').boundingBox())!.y - top)).toBeLessThan(2);
  await expect(tabs).toBeInViewport();

  // Search narrows the list without losing the search box's focus.
  const search = yard.getByRole('searchbox', { name: 'Search rules' });
  await search.fill('multiple lines');
  await expect(search).toBeFocused();
  await expect(yard.locator('.yard-list .yard-row')).toHaveCount(1);
  await expect(yard.locator('[data-yard-count]')).toHaveText('1 active rule');
  await search.fill('');

  // Retire asks first; Escape backs out without closing Settings.
  const row = yard.locator('.yard-row', { hasText: 'Write method definitions over multiple lines.' });
  await row.hover();
  await row.getByRole('button', { name: 'Retire' }).click();
  await expect(row.getByRole('button', { name: 'Confirm retire' })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(row.getByRole('button', { name: 'Retire' })).toBeVisible();
  await expect(page.locator('.settings-overlay.active')).toBeVisible();

  // Maintenance sits at the right end of the Pipeline bar, not on other views.
  await tabs.getByRole('tab', { name: 'Pipeline' }).click();
  const maintenance = yard.locator('.yard-bar [data-yard-action="maintenance"]');
  await expect(maintenance).toHaveText(/^Consolidate \d+ captured · \d+ candidates?$/);
  const bar = (await yard.locator('.yard-bar').boundingBox())!;
  const button = (await maintenance.boundingBox())!;
  expect(bar.x + bar.width - (button.x + button.width)).toBeLessThan(40);
  await tabs.getByRole('tab', { name: 'Health' }).click();
  await expect(yard.locator('[data-yard-action="maintenance"]')).toHaveCount(0);
});

test('a view that fails to load says so and can be retried', async ({ page }) => {
  let fail = true;
  await page.route('**/api/preferences/loads', (route) => (fail ? route.fulfill({ status: 500, body: 'store unavailable' }) : route.continue()));
  await page.goto('/');
  await expect(page.locator('.loading')).toBeHidden();
  await page.click('#settingsToggle');
  await page.click('#tab-yard');
  const yard = page.locator('#yardPane .yard');
  await yard.getByRole('tab', { name: 'Loads' }).click();
  const alert = yard.getByRole('alert');
  await expect(alert).toContainText('Could not load Loads');
  fail = false;
  await alert.getByRole('button', { name: 'Retry' }).click();
  await expect(yard.getByRole('alert')).toHaveCount(0);
});

test('picking a persona file keeps the file list where it was', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('.loading')).toBeHidden();
  await page.click('#settingsToggle');
  await page.click('#tab-yard');
  const yard = page.locator('#yardPane .yard');
  await yard.getByRole('tab', { name: 'Persona' }).click();
  const tree = yard.locator('.yard-tree');
  await expect(tree.locator('[data-persona-file="core.md"]')).toBeVisible();
  await tree.evaluate((el) => {
    (el as HTMLElement & { __kept?: boolean }).__kept = true;
    el.style.maxHeight = '40px';
    el.scrollTop = 20;
  });
  await tree.locator('[data-persona-file="ruby.md"]').click();
  await expect(yard.locator('.yard-file-view')).toContainText('multiple lines');
  expect(await tree.evaluate((el) => (el as HTMLElement & { __kept?: boolean }).__kept === true)).toBe(true);
  // Not rebuilt, so not thrown back to the top of the list.
  expect(await tree.evaluate((el) => el.scrollTop)).toBeGreaterThan(0);
  await expect(tree.locator('[data-persona-file="ruby.md"]')).toHaveAttribute('aria-current', 'true');
  await expect(tree.locator('[data-persona-file="ruby.md"]')).toBeFocused();
});

