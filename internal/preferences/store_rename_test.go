func TestOpenMovesLegacyStore(t *testing.T) {
	writeState := func(t *testing.T, dir, content string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Join(dir, "generations", "g-1"), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, "state.json"), []byte(content), 0600); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink("generations/g-1", filepath.Join(dir, "current")); err != nil {
			t.Fatal(err)
		}
	}
	tests := []struct {
		name       string
		legacy     bool
		current    bool
		wantState  string
		wantLegacy bool
	}{
		{"legacy store moves to hunkyard-preferences", true, false, "legacy", false},
		{"an existing hunkyard-preferences store wins", true, true, "current", true},
		{"no store stays empty", false, false, "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			if tt.legacy {
				writeState(t, filepath.Join(root, "learn-preferences"), "legacy")
			}
			if tt.current {
				writeState(t, filepath.Join(root, "hunkyard-preferences"), "current")
			}
			s, err := Open(Config{Root: root})
			if err != nil {
				t.Fatal(err)
			}
			if got := s.dataPath("state.json"); got != filepath.Join(root, "hunkyard-preferences", "state.json") {
				t.Fatalf("data path = %s", got)
			}
			data, _ := os.ReadFile(s.dataPath("state.json"))
			if string(data) != tt.wantState {
				t.Fatalf("state = %q, want %q", data, tt.wantState)
			}
			if tt.wantState != "" {
				if info, err := os.Stat(s.dataPath("current")); err != nil || !info.IsDir() {
					t.Fatalf("current generation link broke: %v", err)
				}
			}
			if _, err := os.Lstat(filepath.Join(root, "learn-preferences")); (err == nil) != tt.wantLegacy {
				t.Fatalf("legacy folder present = %v, want %v", err == nil, tt.wantLegacy)
			}
		})
	}
}

func TestPreferencesHomeVariable(t *testing.T) {
	home := t.TempDir()
	setHome(t, home)
	t.Setenv("LEARN_PREFERENCES_HOME", filepath.Join(home, "old"))
	t.Setenv("HUNKYARD_PREFERENCES_HOME", filepath.Join(home, "new"))
	if config, err := resolveConfig(Config{}); err != nil || config.Root != filepath.Join(home, "new") {
		t.Fatalf("HUNKYARD_PREFERENCES_HOME precedence: %#v, %v", config.Root, err)
	}
	t.Setenv("HUNKYARD_PREFERENCES_HOME", "")
	if config, err := resolveConfig(Config{}); err != nil || config.Root != filepath.Join(home, "old") {
		t.Fatalf("LEARN_PREFERENCES_HOME fallback: %#v, %v", config.Root, err)
	}
}

func TestLegacyGeneratedHeadersStayReplaceable(t *testing.T) {
	s := testStore(t)
	persona := filepath.Join(s.config.Root, "persona", "core.md")
	if err := os.MkdirAll(filepath.Dir(persona), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(persona, []byte("<!-- Generated by learn-preferences; do not edit. -->\nold rules\n"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(s.dataPath(), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(s.dataPath("source-packs.yml"), []byte("# Generated by learn-preferences; do not edit.\nschema_version: 1\npacks: {}\n"), 0600); err != nil {
		t.Fatal(err)
	}
	if _, err := s.commitGeneration(emptyGeneration()); err != nil {
		t.Fatal(err)
	}
	if s.mirrorError != nil {
		t.Fatalf("a file with the old generated header was treated as hand-written: %v", s.mirrorError)
	}
	for _, path := range []string{persona, s.dataPath("source-packs.yml")} {
		data, err := os.ReadFile(path)
		if err != nil || string(data[:30]) == "<!-- Generated by learn-prefer" || string(data[:30]) == "# Generated by learn-preferenc" {
			t.Fatalf("%s was not regenerated: %q %v", path, data, err)
		}
	}
}

func TestDoctorWarnsAboutLegacyStoreBesideTheNewOne(t *testing.T) {
	s := testStore(t)
	if check := doctorCheck(s.doctor(), "legacy_store"); check != nil {
		t.Fatalf("legacy_store reported without an old folder: %v", check)
	}
	// An older Hunkyard still running after the upgrade recreates the old
	// folder and writes there; the new store never sees it.
	legacy := filepath.Join(s.config.Root, "learn-preferences", "observations")
	if err := os.MkdirAll(legacy, 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(legacy, "pending.jsonl"), []byte("{}\n"), 0600); err != nil {
		t.Fatal(err)
	}
	check := doctorCheck(s.doctor(), "legacy_store")
	if check == nil || check["status"] != "warn" || !strings.Contains(textField(check["detail"]), "learn-preferences") {
		t.Fatalf("old folder beside the store not reported: %v", check)
	}
}
