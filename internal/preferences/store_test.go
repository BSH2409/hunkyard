func TestGenerationRollbackAndMirrorRepair(t *testing.T) {
	s := testStore(t)
	first := emptyGeneration()
	first.Manifest["generation_id"] = "g-first"
	if _, err := s.commitGeneration(first); err != nil {
		t.Fatal(err)
	}
	second := emptyGeneration()
	second.Manifest["generation_id"] = "g-second"
	second.PersonaFiles["core.md"] += "second generation\n"
	if _, err := s.commitGeneration(second); err != nil {
		t.Fatal(err)
	}
	if err := s.rollback("g-first"); err != nil {
		t.Fatal(err)
	}
	current, err := s.loadCurrent()
	if err != nil || current == nil || current.ID != "g-first" {
		t.Fatalf("rollback: %v", err)
	}
	if err := os.Remove(filepath.Join(s.config.Root, "persona", "core.md")); err != nil {
		t.Fatal(err)
	}
	if err := s.repairMirrors(); err != nil {
		t.Fatal(err)
	}
	content, err := os.ReadFile(filepath.Join(s.config.Root, "persona", "core.md"))
	if err != nil || string(content) != first.PersonaFiles["core.md"] {
		t.Fatalf("mirror repair: %v", err)
	}
	if err := s.rollback("../../outside"); err == nil {
		t.Fatal("escaping rollback accepted")
	}
}

func TestGenerationMirrorValidatesObsoleteFilesBeforeApplying(t *testing.T) {
	s := testStore(t)
	first := emptyGeneration()
	first.Manifest["generation_id"] = "g-first"
	first.PersonaFiles["ruby.md"] = generatedHeader + "\n- Keep methods focused.\n"
	if _, err := s.commitGeneration(first); err != nil {
		t.Fatal(err)
	}
	obsolete := filepath.Join(s.config.Root, "persona", "ruby.md")
	if err := os.WriteFile(obsolete, []byte("manually replaced content"), 0600); err != nil {
		t.Fatal(err)
	}
	next := emptyGeneration()
	next.Manifest["generation_id"] = "g-next"
	next.PersonaFiles["core.md"] += "- New guidance.\n"
	if _, err := s.commitGeneration(next); err != nil {
		t.Fatal(err)
	}
	if s.mirrorError == nil {
		t.Fatal("manually replaced obsolete file was not reported")
	}
	core, err := os.ReadFile(filepath.Join(s.config.Root, "persona", "core.md"))
	if err != nil || string(core) != first.PersonaFiles["core.md"] {
		t.Fatal("persona mirror partially applied before validation")
	}
}
