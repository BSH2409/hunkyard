func TestGenerationConcurrency(t *testing.T) {
	if root := os.Getenv("HUNKYARD_PREFERENCES_TEST_ROOT"); root != "" {
		s, err := Open(Config{Root: root})
		if err != nil {
			t.Fatal(err)
		}
		for i := 0; i < 5; i++ {
			err = s.withGenerationLock(func() error {
				current, err := s.loadCurrent()
				if err != nil {
					return err
				}
				next := emptyGeneration()
				count := 0
				if current != nil {
					count, _ = integer(current.Manifest["counter"])
				}
				next.Manifest["counter"] = count + 1
				_, err = s.commitLocked(next)
				return err
			})
			if err != nil {
				t.Fatal(err)
			}
		}
		return
	}
	s := testStore(t)
	var group sync.WaitGroup
	for i := 0; i < 2; i++ {
		group.Add(1)
		go func() {
			defer group.Done()
			command := exec.Command(os.Args[0], "-test.run=^TestGenerationConcurrency$", "-test.count=1")
			command.Env = append(os.Environ(), "HUNKYARD_PREFERENCES_TEST_ROOT="+s.config.Root)
			if output, err := command.CombinedOutput(); err != nil {
				t.Errorf("child failed: %s: %v", output, err)
			}
		}()
	}
	group.Wait()
	current, err := s.loadCurrent()
	if err != nil {
		t.Fatal(err)
	}
	if current == nil {
		t.Fatal("no generation published")
	}
	if count, ok := integer(current.Manifest["counter"]); !ok || count != 10 {
		t.Fatalf("lost concurrent transaction: %v", current.Manifest["counter"])
	}
}

