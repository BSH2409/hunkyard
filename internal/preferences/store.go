const generatedHeader = "<!-- Generated by learn-preferences; do not edit. -->"
const sourceMirrorHeader = "# Generated by learn-preferences; do not edit.\n"

var generationIDPattern = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9._-]*$`)
var sha256Pattern = regexp.MustCompile(`^[0-9a-f]{64}$`)
var repositoryKeyPattern = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,63}-[0-9a-f]{12}$`)

type Store struct {
	config        Config
	hostKind      string
	fault         func(string) error
	mirrorError   error
	legacyPersona map[string]string
}

type validatedRuleSet struct {
	issuer *Store
	rules  []rule
}

type generation struct {
	ID           string
	Rules        validatedRuleSet
	ProcessedIDs []string
	SourcePacks  map[string]any
	PersonaFiles map[string]string
	Manifest     map[string]any
}

func Open(config Config) (*Store, error) {
	config, err := resolveConfig(config)
	if err != nil {
		return nil, err
	}
	return &Store{config: config}, nil
}

func (s *Store) dataPath(parts ...string) string {
	return filepath.Join(append([]string{s.config.Root, "learn-preferences"}, parts...)...)
}

func (s *Store) interrupt(stage string) error {
	if s.fault != nil {
		return s.fault(stage)
	}
	return nil
}

func ensureDirectory(name string) error {
	info, err := os.Lstat(name)
	if err == nil {
		if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("preference directory must not be a symlink or non-directory")
		}
		return nil
	}
	if !os.IsNotExist(err) {
		return err
	}
	parent := filepath.Dir(name)
	if parent == name {
		return err
	}
	if err := ensureDirectory(parent); err != nil {
		return err
	}
	if err := os.Mkdir(name, 0700); err != nil && !os.IsExist(err) {
		return err
	}
	info, err = os.Lstat(name)
	if err != nil {
		return err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("invalid preference directory")
	}
	return nil
}

func regularFile(name string) ([]byte, error) {
	info, err := os.Lstat(name)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("canonical artifact must be a regular file")
	}
	return os.ReadFile(name)
}

func writeNewFile(name string, data []byte) error {
	file, err := os.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	_, writeErr := file.Write(data)
	if writeErr == nil {
		writeErr = file.Sync()
	}
	return errors.Join(writeErr, file.Close())
}

// Package tests instrument this boundary to verify parent-directory durability.
var syncDirectory = func(name string) error {
	dir, err := os.Open(name)
	if err != nil {
		return err
	}
	defer dir.Close()
	return syncDirectoryFile(dir)
}

func (s *Store) withGenerationLock(fn func() error) error {
	if err := ensureDirectory(s.dataPath("generations")); err != nil {
		return err
	}
	if err := checkDirectoryChain(s.config.Root, s.dataPath("generations")); err != nil {
		return err
	}
	return withFileLock(s.dataPath(".generation.lock"), false, fn)
}

func withFileLock(name string, nonblocking bool, fn func() error) error {
	if err := ensureDirectory(filepath.Dir(name)); err != nil {
		return err
	}
	if info, err := os.Lstat(name); err == nil && !info.Mode().IsRegular() {
		return fmt.Errorf("lock must be a regular file")
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	file, err := os.OpenFile(name, os.O_RDWR|os.O_CREATE, 0600)
	if err != nil {
		return err
	}
	defer file.Close()
	if err := file.Chmod(0600); err != nil {
		return err
	}
	if err := lockFile(file, nonblocking); err != nil {
		return err
	}
	defer unlockFile(file)
	return fn()
}

func safeRelative(name string) bool {
	return name != "" && name != "." && name != ".." && !strings.ContainsAny(name, "\\\x00") && !strings.Contains(name, ":") && !path.IsAbs(name) && path.Clean(name) == name && !strings.HasPrefix(name, "../")
}

func (s *Store) loadCurrent() (*generation, error) {
	if err := checkDirectoryChain(s.config.Root, s.dataPath()); err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	name := s.dataPath("current")
	info, err := os.Lstat(name)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	if info.Mode()&os.ModeSymlink == 0 {
		return nil, fmt.Errorf("current must be a relative generation symlink")
	}
	target, err := os.Readlink(name)
	if err != nil {
		return nil, err
	}
	id := strings.TrimPrefix(filepath.ToSlash(target), "generations/")
	if target != "generations/"+id || !generationIDPattern.MatchString(id) || strings.Contains(id, "..") {
		return nil, fmt.Errorf("current must name one relative generation")
	}
	if err := checkDirectoryChain(s.config.Root, s.dataPath("generations")); err != nil {
		return nil, err
	}
	return s.loadGeneration(s.dataPath("generations", id), id)
}

func generationDigests(root string) (map[string]string, error) {
	info, err := os.Lstat(root)
	if err != nil {
		return nil, err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return nil, fmt.Errorf("generation must be a directory")
	}
	digests := map[string]string{}
	err = filepath.WalkDir(root, func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("generation contains a non-regular artifact")
		}
		relative, err := filepath.Rel(root, name)
		if err != nil {
			return err
		}
		relative = filepath.ToSlash(relative)
		if relative == "manifest.json" {
			return nil
		}
		data, err := regularFile(name)
		if err != nil {
			return err
		}
		digests[relative] = digest(string(data))
		return nil
	})
	return digests, err
}

//nolint:gocyclo // Generation publication and mirror recovery keep their filesystem guards in one transaction.
func (s *Store) loadGeneration(dir, id string) (*generation, error) {
	actual, err := generationDigests(dir)
	if err != nil {
		return nil, err
	}
	manifestBytes, err := regularFile(filepath.Join(dir, "manifest.json"))
	if err != nil {
		return nil, err
	}
	manifest := map[string]any{}
	if err := strictjson.Decode(manifestBytes, &manifest); err != nil {
		return nil, err
	}
	version, valid := integer(manifest["schema_version"])
	if !valid || version != schemaVersion || manifest["generation_id"] != id {
		return nil, fmt.Errorf("invalid generation manifest schema")
	}
	expected, ok := manifest["files"].(map[string]any)
	if !ok || len(expected) != len(actual) {
		return nil, fmt.Errorf("invalid manifest digests")
	}
	for name, hash := range expected {
		text, ok := hash.(string)
		if !ok || !safeRelative(name) || !sha256Pattern.MatchString(text) || actual[name] != text {
			return nil, fmt.Errorf("generation digest mismatch")
		}
	}
	readDocument := func(name, key string, out any) error {
		data, err := regularFile(filepath.Join(dir, name))
		if err != nil {
			return err
		}
		var document map[string]any
		if err := decodeYAML(data, &document); err != nil {
			return err
		}
		if err := exactFields(document, []string{"schema_version", key}, nil); err != nil {
			return err
		}
		version, ok := integer(document["schema_version"])
		if !ok || version != schemaVersion {
			return fmt.Errorf("invalid canonical YAML schema")
		}
		encoded, err := canonicalJSON(document[key])
		if err != nil {
			return err
		}
		return strictjson.Decode(encoded, out)
	}
	var rules []rule
	if err := readDocument("rules.yml", "rules", &rules); err != nil {
		return nil, err
	}
	if rules == nil {
		return nil, fmt.Errorf("rules must be an array")
	}
	if err := validateRuleGraph(rules); err != nil {
		return nil, err
	}
	derived, err := normalizeRules(rules, s.config.Clock())
	if err != nil {
		return nil, err
	}
	// Aging takes effect on publication; time cannot invalidate an immutable generation.
	for i, r := range derived {
		if r["id"] == rules[i]["id"] && r["status"] == "dormant" && rules[i]["status"] == "candidate" {
			r["status"] = "candidate"
		}
	}
	if !canonicalEqual(derived, rules) {
		return nil, fmt.Errorf("rules are not canonical")
	}
	if !sort.SliceIsSorted(rules, func(i, j int) bool { return rules[i]["id"].(string) < rules[j]["id"].(string) }) {
		return nil, fmt.Errorf("rules are not canonical")
	}
	var processed []string
	if err := readDocument("processed-observations.yml", "ids", &processed); err != nil {
		return nil, err
	}
	if processed == nil || !reflect.DeepEqual(processed, sortedUnique(processed)) {
		return nil, fmt.Errorf("processed ids are not canonical")
	}
	for _, entry := range processed {
		if entry == "" {
			return nil, fmt.Errorf("processed id cannot be empty")
		}
	}
	var packs map[string]any
	if err := readDocument("source-packs.yml", "packs", &packs); err != nil {
		return nil, err
	}
	if err := validateSourceMetadata(packs, rules); err != nil {
		return nil, err
	}
	names, err := stringArray(manifest["persona_files"])
	if err != nil || !reflect.DeepEqual(names, sortedUnique(names)) {
		return nil, fmt.Errorf("invalid persona file manifest")
	}
	files := map[string]string{}
	for _, name := range names {
		if !safeRelative(name) {
			return nil, fmt.Errorf("invalid persona path")
		}
		content, err := regularFile(filepath.Join(dir, "persona", filepath.FromSlash(name)))
		if err != nil {
			return nil, err
		}
		files[name] = string(content)
	}
	return &generation{ID: id, Rules: validatedRuleSet{issuer: s, rules: rules}, ProcessedIDs: processed, SourcePacks: packs, PersonaFiles: files, Manifest: manifest}, nil
}

func (s *Store) commitGeneration(next generation) (string, error) {
	var id string
	err := s.withGenerationLock(func() error { var err error; id, err = s.commitLocked(next); return err })
	return id, err
}

//nolint:gocyclo // Generation publication and mirror recovery keep their filesystem guards in one transaction.
func (s *Store) commitLocked(next generation) (string, error) {
	current, err := s.loadCurrent()
	if err != nil {
		return "", err
	}
	rules := next.Rules.rules
	if rules == nil {
		rules = []rule{}
	}
	if next.Rules.issuer != s && !(len(rules) == 0 && current == nil) && !(current != nil && canonicalEqual(rules, current.Rules.rules)) {
		return "", fmt.Errorf("raw rules must match the validated current generation")
	}
	if err := validateRuleGraph(rules); err != nil {
		return "", err
	}
	if err := validateSourceMetadata(next.SourcePacks, rules); err != nil {
		return "", err
	}
	rules, err = normalizeRules(rules, s.config.Clock())
	if err != nil {
		return "", err
	}
	sort.Slice(rules, func(i, j int) bool { return rules[i]["id"].(string) < rules[j]["id"].(string) })
	ids := sortedUnique(next.ProcessedIDs)
	for _, id := range ids {
		if id == "" {
			return "", fmt.Errorf("processed id cannot be empty")
		}
	}
	personaPaths := make([]string, 0, len(next.PersonaFiles))
	for name := range next.PersonaFiles {
		if !safeRelative(name) {
			return "", fmt.Errorf("invalid persona path")
		}
		personaPaths = append(personaPaths, name)
	}
	sort.Strings(personaPaths)
	manifest := cloneMap(next.Manifest)
	material := map[string]any{"rules": rules, "processed_ids": ids, "source_packs": next.SourcePacks, "persona_files": next.PersonaFiles, "manifest": cloneMap(manifest)}
	delete(material["manifest"].(map[string]any), "generation_id")
	bytes, err := canonicalJSON(material)
	if err != nil {
		return "", err
	}
	id := "g-" + s.config.Clock().UTC().Format("20060102T150405.000000Z") + "-" + digest(string(bytes))[:12]
	// The reference timestamp has six microsecond digits without a separator.
	id = strings.ReplaceAll(id, ".", "")
	if named, ok := manifest["generation_id"]; ok {
		var valid bool
		id, valid = named.(string)
		if !valid {
			return "", fmt.Errorf("invalid generation id")
		}
	}
	if !generationIDPattern.MatchString(id) || strings.Contains(id, "..") {
		return "", fmt.Errorf("invalid generation id")
	}
	final := s.dataPath("generations", id)
	if _, err := os.Lstat(final); !os.IsNotExist(err) {
		if err != nil {
			return "", err
		}
		return "", fmt.Errorf("generation already exists")
	}
	staging, err := os.MkdirTemp(s.dataPath("generations"), ".tmp-"+id+"-")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(staging)
	documents := map[string]any{"rules.yml": map[string]any{"schema_version": schemaVersion, "rules": rules}, "processed-observations.yml": map[string]any{"schema_version": schemaVersion, "ids": ids}, "source-packs.yml": map[string]any{"schema_version": schemaVersion, "packs": next.SourcePacks}}
	for name, document := range documents {
		data, err := yaml.Marshal(document)
		if err != nil {
			return "", err
		}
		if err := writeNewFile(filepath.Join(staging, name), data); err != nil {
			return "", err
		}
	}
	if err := ensureDirectory(filepath.Join(staging, "persona")); err != nil {
		return "", err
	}
	for _, name := range personaPaths {
		target := filepath.Join(staging, "persona", filepath.FromSlash(name))
		if err := ensureDirectory(filepath.Dir(target)); err != nil {
			return "", err
		}
		if err := writeNewFile(target, []byte(next.PersonaFiles[name])); err != nil {
			return "", err
		}
	}
	digests, err := generationDigests(staging)
	if err != nil {
		return "", err
	}
	manifest["schema_version"] = schemaVersion
	manifest["generation_id"] = id
	manifest["files"] = digests
	manifest["persona_files"] = personaPaths
	encoded, err := canonicalJSON(manifest)
	if err != nil {
		return "", err
	}
	if err := s.interrupt("before_flush"); err != nil {
		return "", err
	}
	if err := writeNewFile(filepath.Join(staging, "manifest.json"), append(encoded, '\n')); err != nil {
		return "", err
	}
	if err := syncGeneration(staging); err != nil {
		return "", err
	}
	if _, err := s.loadGeneration(staging, id); err != nil {
		return "", err
	}
	if err := s.interrupt("before_rename"); err != nil {
		return "", err
	}
	if err := s.interrupt("before_swap"); err != nil {
		return "", err
	}
	if err := os.Rename(staging, final); err != nil {
		return "", err
	}
	if err := syncDirectory(s.dataPath("generations")); err != nil {
		return "", err
	}
	if err := s.swapCurrent(id); err != nil {
		return "", err
	}
	// Publication is authoritative; mirror errors are repairable, never a rollback.
	s.mirrorError = s.interrupt("before_mirror")
	if s.mirrorError == nil {
		s.mirrorError = s.refreshMirrors(next.PersonaFiles, next.SourcePacks, current)
	}
	return id, nil
}

func syncGeneration(root string) error {
	var dirs []string
	err := filepath.WalkDir(root, func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			dirs = append(dirs, name)
			return nil
		}
		return os.Chmod(name, 0400)
	})
	if err != nil {
		return err
	}
	for i := len(dirs) - 1; i >= 0; i-- {
		if err := syncDirectory(dirs[i]); err != nil {
			return err
		}
	}
	return nil
}

func (s *Store) swapCurrent(id string) error {
	temp, err := os.CreateTemp(s.dataPath(), ".current-")
	if err != nil {
		return err
	}
	name := temp.Name()
	if err := temp.Close(); err != nil {
		os.Remove(name)
		return err
	}
	if err := os.Remove(name); err != nil {
		return err
	}
	defer os.Remove(name)
	if err := os.Symlink("generations/"+id, name); err != nil {
		return fmt.Errorf("relative generation symlinks are required: %w", err)
	}
	if err := os.Rename(name, s.dataPath("current")); err != nil {
		return err
	}
	return syncDirectory(s.dataPath())
}

func (s *Store) refreshMirrors(files map[string]string, packs map[string]any, previous *generation) error {
	personaErr := s.refreshPersonaMirror(files, previous)
	sourceErr := s.refreshSourceMirror(packs)
	return errors.Join(personaErr, sourceErr)
}

//nolint:gocyclo // Generation publication and mirror recovery keep their filesystem guards in one transaction.
func (s *Store) refreshPersonaMirror(files map[string]string, previous *generation) error {
	root := filepath.Join(s.config.Root, "persona")
	if err := ensureDirectory(root); err != nil {
		return err
	}
	old := map[string]string{}
	if previous != nil {
		old = previous.PersonaFiles
	}
	stage, err := os.MkdirTemp(s.dataPath(), ".persona-mirror-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	for name, content := range files {
		if !safeRelative(name) {
			return fmt.Errorf("invalid persona mirror path")
		}
		target := filepath.Join(root, filepath.FromSlash(name))
		if err := ensureDirectory(filepath.Dir(target)); err != nil {
			return err
		}
		if err := checkDirectoryChain(root, filepath.Dir(target)); err != nil {
			return err
		}
		existing, err := regularFile(target)
		approved, legacy := s.legacyPersona[name]
		if err == nil && string(existing) != old[name] && !strings.HasPrefix(string(existing), generatedHeader) && (!legacy || string(existing) != approved) {
			return fmt.Errorf("refusing to overwrite a hand-written persona")
		}
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		staged := filepath.Join(stage, filepath.FromSlash(name))
		if err := ensureDirectory(filepath.Dir(staged)); err != nil {
			return err
		}
		if err := writeNewFile(staged, []byte(content)); err != nil {
			return err
		}
	}
	for name, expected := range old {
		if _, ok := files[name]; ok {
			continue
		}
		target := filepath.Join(root, filepath.FromSlash(name))
		if err := checkDirectoryChain(root, filepath.Dir(target)); err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return err
		}
		existing, err := regularFile(target)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return err
		}
		if string(existing) != expected && !strings.HasPrefix(string(existing), generatedHeader) {
			return fmt.Errorf("refusing to delete a hand-written persona")
		}
	}
	for name := range files {
		target := filepath.Join(root, filepath.FromSlash(name))
		if err := os.Rename(filepath.Join(stage, filepath.FromSlash(name)), target); err != nil {
			return err
		}
		if err := syncDirectory(filepath.Dir(target)); err != nil {
			return err
		}
	}
	for name := range old {
		if _, ok := files[name]; ok {
			continue
		}
		target := filepath.Join(root, filepath.FromSlash(name))
		if err := checkDirectoryChain(root, filepath.Dir(target)); err != nil {
			return err
		}
		content, err := regularFile(target)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return err
		}
		if string(content) == old[name] || strings.HasPrefix(string(content), generatedHeader) {
			if err := os.Remove(target); err != nil {
				return err
			}
			if err := syncDirectory(filepath.Dir(target)); err != nil {
				return err
			}
		}
	}
	return syncDirectory(root)
}

func checkDirectoryChain(root, dir string) error {
	info, err := os.Lstat(root)
	if err != nil {
		return err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("preference root must be a directory")
	}
	relative, err := filepath.Rel(root, dir)
	if err != nil || !safeRelative(filepath.ToSlash(relative)) && relative != "." {
		return fmt.Errorf("mirror path escapes root")
	}
	current := root
	for _, part := range strings.Split(relative, string(filepath.Separator)) {
		if part == "." {
			continue
		}
		current = filepath.Join(current, part)
		info, err := os.Lstat(current)
		if err != nil {
			return err
		}
		if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("mirror parent must be a directory")
		}
	}
	return nil
}

func (s *Store) refreshSourceMirror(packs map[string]any) error {
	target := s.dataPath("source-packs.yml")
	existing, err := regularFile(target)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if len(existing) > 0 {
		if !bytes.HasPrefix(existing, []byte(sourceMirrorHeader)) {
			return fmt.Errorf("refusing to overwrite a hand-written source-pack mirror")
		}
		var document map[string]any
		if err := decodeYAML(existing[len(sourceMirrorHeader):], &document); err != nil {
			return err
		}
		if err := exactFields(document, []string{"schema_version", "packs"}, nil); err != nil {
			return err
		}
		version, ok := integer(document["schema_version"])
		if !ok || version != schemaVersion {
			return fmt.Errorf("invalid source-pack mirror schema")
		}
		currentPacks, ok := document["packs"].(map[string]any)
		if !ok {
			return fmt.Errorf("invalid source-pack mirror")
		}
		if err := validateSourceMetadata(currentPacks, nil); err != nil {
			return err
		}
	}
	document, err := yaml.Marshal(map[string]any{"schema_version": schemaVersion, "packs": packs})
	if err != nil {
		return err
	}
	return atomicReplace(target, append([]byte(sourceMirrorHeader), document...))
}

func (s *Store) rollback(id string) error {
	if !generationIDPattern.MatchString(id) || strings.Contains(id, "..") {
		return fmt.Errorf("invalid rollback generation id")
	}
	return s.withGenerationLock(func() error {
		selected, err := s.loadGeneration(s.dataPath("generations", id), id)
		if err != nil {
			return err
		}
		previous, err := s.loadCurrent()
		if err != nil {
			return err
		}
		if err := s.swapCurrent(id); err != nil {
			return err
		}
		s.mirrorError = s.refreshMirrors(selected.PersonaFiles, selected.SourcePacks, previous)
		return nil
	})
}

func (s *Store) repairMirrors() error {
	return s.withGenerationLock(func() error {
		current, err := s.loadCurrent()
		if err != nil {
			return err
		}
		if current == nil {
			return nil
		}
		s.mirrorError = s.refreshMirrors(current.PersonaFiles, current.SourcePacks, current)
		return s.mirrorError
	})
}

func atomicReplace(target string, content []byte) error {
	temp, err := os.CreateTemp(filepath.Dir(target), ".pending-")
	if err != nil {
		return err
	}
	name := temp.Name()
	defer os.Remove(name)
	if err := temp.Chmod(0600); err != nil {
		temp.Close()
		return err
	}
	_, err = temp.Write(content)
	if err == nil {
		err = temp.Sync()
	}
	err = errors.Join(err, temp.Close())
	if err != nil {
		return err
	}
	if err := os.Rename(name, target); err != nil {
		return err
	}
	return syncDirectory(filepath.Dir(target))
}

func sortedUnique(values []string) []string {
	out := append([]string{}, values...)
	sort.Strings(out)
	result := []string{}
	for _, value := range out {
		if len(result) == 0 || result[len(result)-1] != value {
			result = append(result, value)
		}
	}
	return result
}

func canonicalEqual(a, b any) bool {
	left, err := canonicalJSON(a)
	if err != nil {
		return false
	}
	right, err := canonicalJSON(b)
	return err == nil && bytes.Equal(left, right)
}

func cloneMap(value map[string]any) map[string]any {
	if value == nil {
		return map[string]any{}
	}
	data, err := canonicalJSON(value)
	if err != nil {
		return nil
	}
	var out map[string]any
	if err := strictjson.Decode(data, &out); err != nil {
		return nil
	}
	return out
}

func cloneRules(rules []rule) []rule {
	out := make([]rule, 0, len(rules))
	for _, r := range rules {
		out = append(out, rule(cloneMap(r)))
	}
	return out
}

//nolint:gocyclo // Generation publication and mirror recovery keep their filesystem guards in one transaction.
func validateSourceMetadata(packs map[string]any, rules []rule) error {
	if packs == nil {
		return fmt.Errorf("source packs must be a hash")
	}
	for name, value := range packs {
		pack, ok := value.(map[string]any)
		if !ok || !generationIDPattern.MatchString(name) {
			return fmt.Errorf("invalid source pack")
		}
		if err := exactFields(pack, []string{"digest", "files", "refreshed_at"}, nil); err != nil {
			return err
		}
		hash, ok := pack["digest"].(string)
		if !ok || !sha256Pattern.MatchString(hash) {
			return fmt.Errorf("invalid source pack digest")
		}
		files, ok := pack["files"].(map[string]any)
		if !ok || len(files) == 0 {
			return fmt.Errorf("source pack needs file citations")
		}
		for name, hash := range files {
			text, ok := hash.(string)
			if !safeRelative(name) || !ok || !sha256Pattern.MatchString(text) {
				return fmt.Errorf("invalid source pack citation")
			}
		}
		if err := validateTimestamp(pack["refreshed_at"]); err != nil {
			return err
		}
	}
	for _, r := range rules {
		if r["origin"] != "source_pack" {
			continue
		}
		if r["source_pack"] != "code-like-him" {
			return fmt.Errorf("unsupported source pack")
		}
		pack, ok := packs["code-like-him"].(map[string]any)
		if !ok {
			return fmt.Errorf("source rule lacks persisted metadata")
		}
		ref, ok := r["source_ref"].(map[string]any)
		if !ok {
			return fmt.Errorf("source rule lacks citation")
		}
		files, _ := pack["files"].(map[string]any)
		if hash, ok := files[fmt.Sprint(ref["file"])]; !ok || hash != ref["digest"] {
			return fmt.Errorf("source rule citation does not match metadata")
		}
	}
	return nil
}

func validateTimestamp(value any) error {
	text, ok := value.(string)
	if !ok {
		return fmt.Errorf("timestamp must be an ISO-8601 string")
	}
	_, err := time.Parse(time.RFC3339Nano, text)
	if err != nil {
		return fmt.Errorf("timestamp must be an ISO-8601 string")
	}
	return nil
}
