//go:build ignore

package main

import (
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

func main() {
	_, self, _, ok := runtime.Caller(0)
	if !ok {
		fmt.Fprintln(os.Stderr, "Error locating gen_integration_hashes.go")
		os.Exit(1)
	}
	cmdHunkyardDir := filepath.Dir(self)
	repoRoot := filepath.Join(cmdHunkyardDir, "..", "..")
	integrationsDir := filepath.Join(repoRoot, "integrations")
	outFile := filepath.Join(cmdHunkyardDir, "integration_hashes_gen.go")

	// Keep directly installable and plugin-packaged skills byte-identical.
	copyAsset(filepath.Join(repoRoot, "internal", "preferences", "assets", "maintenance-proposal.json"), filepath.Join(integrationsDir, "preferences", "schemas", "maintenance-proposal.json"))
	for _, dir := range []string{"codex/plugin/hunkyard/skills/learn-preferences", "claude-code/skills/learn-preferences"} {
		for _, name := range []string{"SKILL.md", "references/local-maintenance.md", "schemas/maintenance-proposal.json"} {
			copyAsset(filepath.Join(integrationsDir, "preferences", filepath.FromSlash(name)), filepath.Join(integrationsDir, filepath.FromSlash(dir), filepath.FromSlash(name)))
		}
	}
	for _, name := range []string{"hunkyard", "hunkyard-cli", "hunkyard-story"} {
		copyAsset(filepath.Join(integrationsDir, "codex", "skills", name, "SKILL.md"), filepath.Join(integrationsDir, "codex", "plugin", "hunkyard", "skills", name, "SKILL.md"))
	}
	for _, dir := range []string{"codex/skills/hunkyard", "codex/plugin/hunkyard/skills/hunkyard", "claude-code/skills/hunkyard"} {
		copyAsset(filepath.Join(integrationsDir, "shared", "review-workflow.md"), filepath.Join(integrationsDir, filepath.FromSlash(dir), "references", "review-workflow.md"))
	}
	hashes := map[string]string{}
	err := filepath.Walk(integrationsDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			return nil
		}
		// Skip README files — they're documentation, not installable integrations
		if strings.EqualFold(filepath.Base(path), "README.md") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(repoRoot, path)
		if err != nil {
			return err
		}
		h := sha256.Sum256(data)
		hashes[filepath.ToSlash(rel)] = fmt.Sprintf("%x", h)
		return nil
	})
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error walking integrations: %v\n", err)
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by gen_integration_hashes.go; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("var integrationHashes = map[string]string{\n")

	keys := make([]string, 0, len(hashes))
	for k := range hashes {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, k := range keys {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", k, hashes[k]))
	}
	b.WriteString("}\n")

	// Format with the current Go version's gofmt so the output is stable
	// regardless of which gofmt version checks it later.
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error formatting generated code: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(outFile, formatted, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing generated file: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("Generated integration_hashes_gen.go")
}

func copyAsset(source, dest string) {
	data, err := os.ReadFile(source)
	if err != nil {
		panic(err)
	}
	if err := os.MkdirAll(filepath.Dir(dest), 0755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(dest, data, 0644); err != nil {
		panic(err)
	}
}
